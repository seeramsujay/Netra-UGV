"""Generate the Gazebo terrain model and world from the shared NETRA scenario.

    python3 -m netra_sim.gen_gazebo_assets          (from sim/)
    python3 sim/netra_sim/gen_gazebo_assets.py      (from anywhere)

Writes, relative to sim/:
    models/netra_terrain/{model.config,model.sdf,meshes/terrain.obj}
    worlds/tactical_field.sdf

The terrain mesh uses the same 126 x 91 grid as the Webots ElevationGrid, so
ditch edges, hills and boulder placement are identical across simulators.
"""

import math
import os
import sys

if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from netra_sim import scenario as sc  # noqa: E402

SIM_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD_NAME = "netra_tactical_field"
APRON = 50.0  # flat surround out to +-50 m so the horizon is not a cliff
APRON_THICKNESS = 1.0


def write_terrain_obj(path, grid):
    nx, ny = sc.NX, sc.NY
    xs, ys = sc.grid_xs(), sc.grid_ys()

    def vtx(i, j):
        return (xs[i], ys[j], grid[j * nx + i])

    # Smooth vertex normals from the 4 surrounding central differences.
    normals = []
    for j in range(ny):
        for i in range(nx):
            hl, hr = grid[j * nx + max(i - 1, 0)], grid[j * nx + min(i + 1, nx - 1)]
            hd, hu = grid[max(j - 1, 0) * nx + i], grid[min(j + 1, ny - 1) * nx + i]
            dx = (min(i + 1, nx - 1) - max(i - 1, 0)) * sc.SP
            dy = (min(j + 1, ny - 1) - max(j - 1, 0)) * sc.SP
            n = (-(hr - hl) / dx, -(hu - hd) / dy, 1.0)
            m = math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2)
            normals.append((n[0] / m, n[1] / m, n[2] / m))

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("# NETRA tactical terrain, generated by netra_sim.gen_gazebo_assets\n")
        f.write("o terrain\n")
        for j in range(ny):
            for i in range(nx):
                f.write("v %.4f %.4f %.4f\n" % vtx(i, j))
        for n in normals:
            f.write("vn %.5f %.5f %.5f\n" % n)
        for j in range(ny - 1):
            for i in range(nx - 1):
                a, b = j * nx + i + 1, j * nx + i + 2
                c, d = (j + 1) * nx + i + 1, (j + 1) * nx + i + 2
                f.write("f %d//%d %d//%d %d//%d\n" % (a, a, b, b, d, d))
                f.write("f %d//%d %d//%d %d//%d\n" % (a, a, d, d, c, c))


TERRAIN_CONFIG = """<?xml version="1.0"?>
<model>
  <name>netra_terrain</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>NETRA-UGV Team</name><email>team@netra-ugv.in</email></author>
  <description>50 x 36 m tactical field: hills and four 0.55 m deep negative-obstacle ditches.</description>
</model>
"""

TERRAIN_SDF = """<?xml version="1.0"?>
<sdf version="1.9">
  <model name="netra_terrain">
    <static>true</static>
    <link name="link">
      <collision name="collision">
        <geometry><mesh><uri>model://netra_terrain/meshes/terrain.obj</uri></mesh></geometry>
        <surface>
          <friction><ode><mu>0.9</mu><mu2>0.9</mu2></ode></friction>
        </surface>
      </collision>
      <visual name="visual">
        <geometry><mesh><uri>model://netra_terrain/meshes/terrain.obj</uri></mesh></geometry>
        <material>
          <ambient>0.42 0.36 0.26 1</ambient>
          <diffuse>0.55 0.47 0.33 1</diffuse>
          <specular>0.05 0.05 0.05 1</specular>
        </material>
      </visual>
    </link>
  </model>
</sdf>
"""


def apron_boxes():
    """Four static slabs around the field, top face at z = 0."""
    a, t = APRON, APRON_THICKNESS
    x0, x1, y0, y1 = sc.X0, sc.X1, sc.Y0, sc.Y1
    # (name, cx, cy, size_x, size_y)
    return [
        ("apron_west", (-a + x0) / 2, 0.0, x0 + a, 2 * a),
        ("apron_east", (x1 + a) / 2, 0.0, a - x1, 2 * a),
        ("apron_south", (x0 + x1) / 2, (-a + y0) / 2, x1 - x0, y0 + a),
        ("apron_north", (x0 + x1) / 2, (y1 + a) / 2, x1 - x0, a - y1),
    ], t


def box_model(name, pose, size, rgba, collide=True):
    sx, sy, sz = size
    col = (
        (
            '<collision name="c"><geometry><box><size>%.3f %.3f %.3f</size></box></geometry>'
            "<surface><friction><ode><mu>0.9</mu><mu2>0.9</mu2></ode></friction></surface></collision>" % (sx, sy, sz)
        )
        if collide
        else ""
    )
    return """    <model name="%s">
      <static>true</static>
      <pose>%s</pose>
      <link name="link">
        %s
        <visual name="v"><geometry><box><size>%.3f %.3f %.3f</size></box></geometry>
          <material><ambient>%s</ambient><diffuse>%s</diffuse></material></visual>
      </link>
    </model>
""" % (name, pose, col, sx, sy, sz, rgba, rgba)


def build_world(grid, rocks):
    parts = []
    parts.append("""<?xml version="1.0"?>
<!-- GENERATED by netra_sim.gen_gazebo_assets: edit scenario.py, not this file. -->
<sdf version="1.9">
  <world name="%s">
    <physics name="2ms" type="dart">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <gravity>0 0 -9.81</gravity>
    <scene>
      <ambient>0.45 0.45 0.45 1</ambient>
      <background>0.62 0.74 0.86 1</background>
      <shadows>true</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 30 0 0 0</pose>
      <diffuse>0.9 0.85 0.75 1</diffuse>
      <specular>0.3 0.3 0.3 1</specular>
      <direction>-0.5 0.2 -1.0</direction>
    </light>

    <include>
      <uri>model://netra_terrain</uri>
      <name>terrain</name>
    </include>

""" % WORLD_NAME)

    aprons, t = apron_boxes()
    for name, cx, cy, sx, sy in aprons:
        parts.append(box_model(name, "%.3f %.3f %.3f 0 0 0" % (cx, cy, -t / 2), (sx, sy, t), "0.40 0.35 0.25 1"))

    for i, r in enumerate(rocks):
        lx, ly, lz = r.dims
        z = sc.ground_z(r.x, r.y, grid) + r.size * 0.4
        parts.append(
            box_model(
                "rock_%02d" % i, "%.3f %.3f %.3f 0 0 %.3f" % (r.x, r.y, z, r.yaw), (lx, ly, lz), "0.40 0.40 0.42 1"
            )
        )

    # visual-only mission markers (no collision)
    gx, gy = sc.GOAL
    parts.append("""    <model name="goal_marker">
      <static>true</static>
      <pose>%g %g %.3f 0 0 0</pose>
      <link name="link">
        <visual name="v"><geometry><cylinder><radius>0.8</radius><length>0.05</length></cylinder></geometry>
          <material><ambient>1 0.85 0.1 1</ambient><diffuse>1 0.85 0.1 1</diffuse><emissive>0.6 0.5 0 1</emissive></material></visual>
      </link>
    </model>
""" % (gx, gy, sc.ground_z(gx, gy, grid) + 0.03))
    for i, (wx, wy) in enumerate(sc.WAYPOINTS[:-1]):
        parts.append("""    <model name="waypoint_%d">
      <static>true</static>
      <pose>%g %g %.3f 0 0 0</pose>
      <link name="link">
        <visual name="v"><geometry><cylinder><radius>0.25</radius><length>0.04</length></cylinder></geometry>
          <material><ambient>0.29 0.87 0.5 1</ambient><diffuse>0.29 0.87 0.5 1</diffuse></material></visual>
      </link>
    </model>
""" % (i + 1, wx, wy, sc.ground_z(wx, wy, grid) + 0.03))

    parts.append("  </world>\n</sdf>\n")
    return "".join(parts)


def main():
    grid = sc.height_grid()
    rocks = sc.build_rocks()

    tdir = os.path.join(SIM_DIR, "models", "netra_terrain")
    write_terrain_obj(os.path.join(tdir, "meshes", "terrain.obj"), grid)
    with open(os.path.join(tdir, "model.config"), "w") as f:
        f.write(TERRAIN_CONFIG)
    with open(os.path.join(tdir, "model.sdf"), "w") as f:
        f.write(TERRAIN_SDF)

    os.makedirs(os.path.join(SIM_DIR, "worlds"), exist_ok=True)
    wpath = os.path.join(SIM_DIR, "worlds", "tactical_field.sdf")
    with open(wpath, "w") as f:
        f.write(build_world(grid, rocks))
    print("wrote %s and %s (%d rocks)" % (os.path.join(tdir, "meshes", "terrain.obj"), wpath, len(rocks)))


if __name__ == "__main__":
    main()
